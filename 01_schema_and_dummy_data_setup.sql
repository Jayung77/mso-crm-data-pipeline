USE practice;

-- 1. 기존 테이블 초기화
DROP TABLE IF EXISTS crm_transaction_log;
DROP TABLE IF EXISTS customer_master;

-- [테이블 1] 회원 마스터 테이블 (기준 정보)
CREATE TABLE customer_master (
    Chart_No VARCHAR(20) PRIMARY KEY, -- 차트번호 (고유키)
    Customer_ID VARCHAR(20),          -- 고객번호
    Customer_Name VARCHAR(20),        -- 고객명 (가명 처리)
    Phone_Number VARCHAR(20),         -- 연락처
    Customer_Grade VARCHAR(20),       -- 고객등급 (VIP, 우수, 일반)
    Join_Date DATE                    -- 최초 등록일
);

-- [테이블 2] 예약 및 거래 트랜잭션 테이블 
CREATE TABLE crm_transaction_log (
    Reservation_Date DATE,            -- 예약일자
    Reservation_Time TIME,            -- 예약시간
    Chart_No VARCHAR(20),             -- 차트번호
    Is_First_Visit VARCHAR(5),        -- 신환여부 (Y/N)
    Inflow_Channel VARCHAR(50),       -- 유입경로
    Consultant_ID VARCHAR(20),        -- 상담실장 ID
    Reservation_Status VARCHAR(20),   -- 예약상태 (진료완료, 예약취소, 노쇼)
    Treatment_Item VARCHAR(50),       -- 진료과목
    Payment_Amount INT,               -- 당일 결제금액
    Unpaid_Amount INT                 -- 미수 잔금
);

